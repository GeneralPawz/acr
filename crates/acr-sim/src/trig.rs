pub fn cos(dir: u8) -> i32 {
    i32::from(TCOS[usize::from(dir)])
}

pub fn sin(dir: u8) -> i32 {
    i32::from(TSIN[usize::from(dir)])
}

/// `Norma` (0x427210): the engine's octagonal distance `(max(|dx|,|dy|) + |dx| + |dy|) / 2`.
pub fn norma(dx: i32, dy: i32) -> i32 {
    let (ax, ay) = (dx.unsigned_abs(), dy.unsigned_abs());
    (ax.max(ay).wrapping_add(ax).wrapping_add(ay) >> 1) as i32
}

/// `GetDir` (0x503df1): direction of the vector `(dx, dy)`; `(0, 0)` gives 192 (north).
pub fn get_dir(dx: i32, dy: i32) -> u8 {
    if dx == 0 && dy == 0 {
        return 192;
    }
    let (adx, ady) = (dx.abs(), dy.abs());
    let atg = |i: i32| i32::from(TATG[i as usize] as u8);
    let mut d = if adx > ady { atg((ady << 8) / adx) } else { 64 - atg((adx << 8) / ady) };
    if dx < 0 {
        d = 128 - d;
    }
    if dy < 0 {
        d = 256 - d;
    }
    (d + 1024) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_quirks_match_the_engine() {
        assert_eq!((cos(0), sin(0)), (256, 0));
        assert_eq!((cos(64), sin(64)), (0, 255));
        assert_eq!((cos(128), sin(128)), (-255, 0));
        assert_eq!((cos(192), sin(192)), (0, -255));
        assert_eq!((cos(32), sin(32)), (181, 181));
        assert_eq!(TATG[256], 31);
    }

    #[test]
    fn directions() {
        assert_eq!(get_dir(10, 0), 0);
        assert_eq!(get_dir(0, 10), 64);
        assert_eq!(get_dir(-10, 0), 128);
        assert_eq!(get_dir(0, -10), 192);
        // TAtg[256] is 31, so exact diagonals come out one step off, as in the engine.
        assert_eq!(get_dir(10, 10), 33);
        assert_eq!(get_dir(0, 0), 192);
        for d in 0..=255u8 {
            let back = get_dir(cos(d) * 16, sin(d) * 16);
            assert!((back.wrapping_sub(d) as i8).abs() <= 1, "{d} -> {back}");
        }
    }

    #[test]
    fn norma_is_octagonal() {
        assert_eq!(norma(10, 0), 10);
        assert_eq!(norma(10, 10), 15);
        assert_eq!(norma(-3, 4), 5);
    }
}
