//! truncates them with `_ftol`: `TSin[i] = trunc(256·sin(i·K))`, `TCos[i] = trunc(256·cos(i·K))`
//! and `TAtg[i] = trunc(atan(i/256)·A)`, with the double constants `K = 0.02454369296875`
//! (0x645520, slightly more than 2π/256) and `A = 40.74366482962607` (0x645510, ≈128/π).
