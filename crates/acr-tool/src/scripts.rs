//! Mission/AI script commands: API report, decoder and runtime checks.

use std::collections::BTreeMap;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

use crate::{Command, Result};

pub const COMMANDS: &[Command] = &[
    Command {
        name: "script-api",
        usage: "<game-dir>   (markdown report of the API missions/AI import)",
        run: |a| match a {
            [dir] => script_api(Path::new(dir)),
            _ => Err(crate::WRONG_ARGS.into()),
        },
    },
    Command {
        name: "script-check",
        usage: "<game-dir>   (decode and initialise every mission/AI DLL)",
        run: |a| match a {
            [dir] => script_check(Path::new(dir)),
            _ => Err(crate::WRONG_ARGS.into()),
        },
    },
    Command {
        name: "script-run",
        usage: "<game-dir> <dll> [--ticks N]   (run a DLL, log its game API calls)",
        run: |a| match a {
            [dir, dll] => script_run(Path::new(dir), dll, 1),
            [dir, dll, "--ticks", n] => n.parse().map_err(Into::into).and_then(|n| script_run(Path::new(dir), dll, n)),
            _ => Err(crate::WRONG_ARGS.into()),
        },
    },
];

/// Lists every function the mission/AI DLLs import from the game executable.
fn script_api(dir: &Path) -> Result<()> {
    use acr_script::pe::PeImage;

    let exe = PeImage::parse(&std::fs::read(dir.join("dmcr.exe"))?)?;
    let exported: std::collections::BTreeSet<&str> = exe.exports.iter().filter_map(|e| e.name.as_deref()).collect();

    // function -> (number of DLLs importing it, example DLL)
    let mut uses: BTreeMap<String, (usize, String)> = BTreeMap::new();
    let mut other_dlls: BTreeMap<String, usize> = BTreeMap::new();
    let mut dll_count = 0;
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        for entry in std::fs::read_dir(&d)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            let rel = path.strip_prefix(dir)?.to_string_lossy().replace('\\', "/");
            let is_script = ["AI/", "Missions/", "History_battl/", "UserMissions/"].iter().any(|p| rel.starts_with(p));
            if !is_script || !rel.to_ascii_lowercase().ends_with(".dll") {
                continue;
            }
            let pe = PeImage::parse(&std::fs::read(&path)?).map_err(|e| format!("{rel}: {e}"))?;
            dll_count += 1;
            let mut seen = std::collections::BTreeSet::new();
            for import in &pe.imports {
                if import.dll.eq_ignore_ascii_case("dmcr.exe") {
                    if seen.insert(import.name.to_string()) {
                        let e = uses.entry(import.name.to_string()).or_insert((0, rel.clone()));
                        e.0 += 1;
                    }
                } else {
                    *other_dlls.entry(format!("{}!{}", import.dll.to_ascii_uppercase(), import.name)).or_default() += 1;
                }
            }
        }
    }

    let mut out = io::stdout().lock();
    writeln!(out, "# Mission and AI scripting API\n")?;
    writeln!(out, "Generated by `acr script-api` from {dll_count} mission/AI DLLs.\n")?;
    writeln!(out, "## Imports from `dmcr.exe` ({} functions)\n", uses.len())?;
    writeln!(out, "| function | used by DLLs | exported by dmcr.exe | example |\n|---|---:|---|---|")?;
    for (name, (count, example)) in &uses {
        let exp = if exported.contains(name.as_str()) { "yes" } else { "**no**" };
        writeln!(out, "| `{name}` | {count} | {exp} | `{example}` |")?;
    }
    writeln!(out, "\n## Other imports\n\n| function | used by DLLs |\n|---|---:|")?;
    for (name, count) in &other_dlls {
        writeln!(out, "| `{name}` | {count} |")?;
    }
    Ok(())
}

/// Mission and AI DLLs of an installation, as paths relative to `dir`.
fn script_dlls(dir: &Path) -> Result<Vec<String>> {
    let mut out = Vec::new();
    let mut stack: Vec<PathBuf> = ["AI", "Missions", "History_battl", "UserMissions"]
        .iter()
        .map(|d| dir.join(d))
        .filter(|d| d.is_dir())
        .collect();
    while let Some(d) = stack.pop() {
        for entry in std::fs::read_dir(&d)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e.eq_ignore_ascii_case("dll")) {
                out.push(path.strip_prefix(dir)?.to_string_lossy().replace('/', "\\"));
            }
        }
    }
    out.sort();
    Ok(out)
}

/// Exports to call after `DllMain`: (init, per-tick).
fn script_entry_points(m: &acr_script::runtime::Machine) -> (&'static str, &'static str) {
    if m.image.export("InitAI").is_some() { ("InitAI", "ProcessAI") } else { ("OnInit", "ProcessScenary") }
}

/// Statically decodes every mission/AI DLL and runs DllMain, the init export and one tick.
fn script_check(dir: &Path) -> Result<()> {
    use acr_script::analysis::reachable_code;
    use acr_script::dmcr::RecordingHost;
    use acr_script::runtime::Machine;

    let dlls = script_dlls(dir)?;
    let (mut insns, mut unsupported, mut attached, mut inited, mut ticked) = (0, 0, 0, 0, 0);
    let mut mnemonics = std::collections::BTreeSet::new();
    println!(
        "{:<52} {:>7} {:>5} {:>7} {:>7} {:>7} {:>5}  result",
        "dll", "insns", "unsup", "attach", "init", "tick", "api"
    );
    for rel in &dlls {
        let mut m = Machine::new(&std::fs::read(dir.join(rel))?, rel)?;
        let cov = reachable_code(&m.mem, &m.image);
        insns += cov.instructions;
        unsupported += cov.unsupported.len();
        mnemonics.extend(cov.mnemonics.into_keys());
        let mut host = RecordingHost::default();
        let (init, tick) = script_entry_points(&m);
        let mut steps = [0u64; 3];
        let mut result = "ok".to_owned();
        let mut stage = 0;
        for (i, name) in ["DllMain", init, tick].into_iter().enumerate() {
            let before = m.steps;
            let r = if i == 0 { m.attach(&mut host).map(u32::from) } else { m.call_export(&mut host, name, &[]) };
            steps[i] = m.steps - before;
            match r {
                Ok(0) if i == 0 => result = "DllMain returned FALSE".into(),
                Ok(_) => {
                    stage = i + 1;
                    continue;
                }
                Err(e) => result = format!("{name}: {e}"),
            }
            break;
        }
        attached += usize::from(stage >= 1);
        inited += usize::from(stage >= 2);
        ticked += usize::from(stage >= 3);
        let unsup = cov.unsupported.first().map(|e| format!(" ({e})")).unwrap_or_default();
        println!(
            "{rel:<52} {:>7} {:>5} {:>7} {:>7} {:>7} {:>5}  {result}{unsup}",
            cov.instructions,
            cov.unsupported.len(),
            steps[0],
            steps[1],
            steps[2],
            host.calls.len()
        );
    }
    println!(
        "\n{} DLLs: {insns} reachable instructions ({} mnemonics), {unsupported} unsupported; \
         DllMain ok {attached}, init ok {inited}, first tick ok {ticked}",
        dlls.len(),
        mnemonics.len()
    );
    Ok(())
}

/// Runs one DLL: DllMain, the init export and `ticks` per-tick calls, printing every game
/// API call.
fn script_run(dir: &Path, dll: &str, ticks: u32) -> Result<()> {
    use acr_script::dmcr::RecordingHost;
    use acr_script::runtime::Machine;

    let rel = dll.replace('/', "\\");
    let mut m = Machine::new(&std::fs::read(dir.join(dll))?, &rel)?;
    let mut host = RecordingHost::default();
    let (init, tick) = script_entry_points(&m);
    let mut out = io::stdout().lock();
    let mut shown = 0;
    let mut stage = |name: &str, m: &mut Machine, host: &mut RecordingHost, out: &mut io::StdoutLock| -> Result<()> {
        let before = m.steps;
        let r = if name == "DllMain" { m.attach(host).map(u32::from) } else { m.call_export(host, name, &[]) };
        writeln!(out, "== {name}: {} instructions, {} API calls", m.steps - before, host.calls.len() - shown)?;
        for c in &host.calls[shown..] {
            writeln!(out, "  {c}")?;
        }
        shown = host.calls.len();
        match r {
            Ok(v) => writeln!(out, "  returned {v:#x}")?,
            Err(e) => {
                writeln!(out, "  error: {e}")?;
                return Err(e.into());
            }
        }
        Ok(())
    };
    stage("DllMain", &mut m, &mut host, &mut out)?;
    stage(init, &mut m, &mut host, &mut out)?;
    for _ in 0..ticks {
        stage(tick, &mut m, &mut host, &mut out)?;
    }
    writeln!(out, "== KERNEL32 calls: {:?}", m.process.calls)?;
    for line in &m.process.output {
        writeln!(out, "== output: {line}")?;
    }
    Ok(())
}
