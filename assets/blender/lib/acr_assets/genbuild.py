"""Buildings and ships from generated models (Tripo, Meshy; needs `bpy`).

The models were generated by the paid services Tripo and Meshy from one sprite view of the
original (buildings: the isometric `#STANDLO` picture; ships: the three-quarter view,
direction 104). They live outside the repo, like every base model:
`$ACR_SOURCES/generated/{tripo,meshy}/<Type>_sprite.glb` (`D:\\ACR-models\\generated` locally,
`/home/claude/sources/generated` on the render VM); Tripo wins where both exist.

`building(ctx, type)` imports one, keeps its base colour and its tangent normal map (both
shrunk to `tex` px; stats `normal_maps`; a source without one gets the relief the decimation
took off baked at `nrm` px, `normal_baked_px`), and fits it to the sprite: `spritefit.fit` searches the turn about +Z (10 degree steps, then the
best four refined) and the uniform scale and ground shift that maximise the silhouette IoU
against the reference `acr model-ref` drew (`ctx.ref`, the ground point at its anchor, so
`LOCATION` is accounted for). The lowest point stands at z = 0. The result is decimated to
`budget` triangles. Without a reference (no game folder) the build stops: the fit needs it.

`ship(ctx, type, length, draft)` turns the model with the same fit (against the reference
view nearest direction 104), snaps its long axis to Y with the bow south, scales it to
`length` metres overall, sinks the keel `draft` below the waterline (the ground point) and
rigs it like `ships.build` (hull > intact / wreck; `STAND`, `MOTION_*`, `ATTACK`, `DEATH`,
`DEATHLIE1`), without sail bones (the generated mesh is one piece). `rel` borrows another
type's generated model (path below `generated/`, e.g. the war canoe ShpKanoe3 on ShpKanoe1's),
still fitted to the own sprite.

Stats: `source`, `source_triangles`, `triangles`, `fit` (yaw, scale, iou of the point
raster), `size_m`, and for ships `length_m`, `height_m`, `draft_m`, `sprite_length_m`
(the length the sprite fit asked for).
"""

import math
import os

import bpy
import numpy as np
from mathutils import Matrix

from . import spritefit
from . import ships as sh
from . import vessels as vs

SERVICES = ("tripo", "meshy")


def source(type_):
    """(service, path) of the generated model of `type_`, Tripo first."""
    root = os.environ.get("ACR_SOURCES")
    if not root:
        raise SystemExit("ACR_SOURCES is not set (folder of extracted base models, see docs/assets.md)")
    for s in SERVICES:
        p = os.path.join(root, "generated", s, f"{type_}_sprite.glb")
        if os.path.exists(p):
            return s, p
    raise SystemExit(f"no generated model for {type_} under {root}/generated")


def _arrays(obj):
    me = obj.data
    me.calc_loop_triangles()
    v = np.empty(len(me.vertices) * 3, np.float64)
    me.vertices.foreach_get("co", v)
    t = np.empty(len(me.loop_triangles) * 3, np.int64)
    me.loop_triangles.foreach_get("vertices", t)
    return v.reshape(-1, 3), t.reshape(-1, 3)


def sample(obj, n=300000, seed=0):
    """`n` points spread over the surface of `obj` by area (seeded)."""
    v, t = _arrays(obj)
    a, b, c = v[t[:, 0]], v[t[:, 1]], v[t[:, 2]]
    area = np.linalg.norm(np.cross(b - a, c - a), axis=1) / 2
    rng = np.random.default_rng(seed)
    idx = rng.choice(len(t), size=n, p=area / area.sum())
    r1, r2 = rng.random(n), rng.random(n)
    flip = r1 + r2 > 1
    r1[flip], r2[flip] = 1 - r1[flip], 1 - r2[flip]
    pts = a[idx] + (b[idx] - a[idx]) * r1[:, None] + (c[idx] - a[idx]) * r2[:, None]
    return np.concatenate([pts, v])


def mask(view):
    """The silhouette (alpha >= 128) of a reference view, rows top-down."""
    img = bpy.data.images.load(view.image)
    w, h = img.size
    px = np.empty(w * h * 4, np.float32)
    img.pixels.foreach_get(px)
    bpy.data.images.remove(img)
    return px.reshape(h, w, 4)[::-1, :, 3] >= 0.5


def _load(ctx, type_, tex, rel=None):
    if rel is None:
        service, path = source(type_)
    else:
        path = os.path.join(os.environ.get("ACR_SOURCES", ""), "generated", rel)
        if not os.path.exists(path):
            raise SystemExit(f"no generated model {rel} under $ACR_SOURCES/generated")
        service = rel.split("/")[0]
    objs = vs.import_file(path)
    tris = vs.triangles(objs)
    vs.base_colour_only(objs, max_size=tex, keep_normal=True)
    ctx.stats["normal_maps"] = sorted({list(img.size)[0] for img in bpy.data.images
                                       if img.users and img.colorspace_settings.name == "Non-Color" and img.size[0]})
    obj = vs.join(objs, f"{ctx.root.name}.model")
    v, _ = _arrays(obj)
    c = (v.min(axis=0) + v.max(axis=0)) / 2
    vs.transform([obj], Matrix.Translation((-c[0], -c[1], -c[2])))
    ctx.stats.update({"source": f"{service}/{os.path.basename(path)}", "source_triangles": tris})
    return obj


def _matrix(f):
    r = Matrix([list(row) for row in spritefit.rot(f["yaw"], f["pitch"])]).to_4x4()
    return (Matrix.Translation((f["shift"][0], f["shift"][1], 0.0)) @ Matrix.Scale(f["scale"], 4)
            @ Matrix.Translation((0.0, 0.0, f["lift"])) @ r)


def _final_iou(obj, m, anchor, real_dir):
    pts = sample(obj, 200000, seed=1)
    uv = spritefit.project(pts, real_dir) + np.asarray(anchor, float)
    return round(spritefit.iou(spritefit.raster(uv, m.shape), m), 3)


def _size(obj):
    v, _ = _arrays(obj)
    return [round(float(x), 2) for x in v.max(axis=0) - v.min(axis=0)]


def _need_ref(ctx):
    if ctx.ref is None:
        raise SystemExit("genbuild fits to the sprite: build with the game folder (ACR_GAME_DIR)")
    return ctx.ref


def bake_normal(high, low, px, name):
    """Bakes the tangent normal map (OpenGL, green +Y: glTF) of `high` onto `low` (its
    decimated copy, same uvs) at `px` and binds it to `low`'s one material; returns the px or
    None (no uvs, several materials, or a normal map kept from the source)."""
    from . import genfit
    from . import nature

    me = low.data
    if not me.uv_layers or len(me.materials) != 1 or me.materials[0] is None:
        return None
    nt = me.materials[0].node_tree
    bsdf = next((n for n in nt.nodes if n.type == "BSDF_PRINCIPLED"), None)
    if bsdf is None or bsdf.inputs["Normal"].links:
        return None
    img = bpy.data.images.new(name + ".nrm", px, px)
    img.generated_color = (0.5, 0.5, 1.0, 1.0)
    img.colorspace_settings.name = "Non-Color"
    node = nt.nodes.new("ShaderNodeTexImage")
    node.name = "genfit.bake"
    node.image = img
    v, _ = _arrays(low)
    size = float((v.max(axis=0) - v.min(axis=0)).max())
    genfit._bake(high, low, img, "NORMAL", max(0.01, 0.005 * size))
    nt.nodes.remove(node)
    img.file_format = "PNG"
    img.pack()
    nature.bind_normal(nt, bsdf, img)
    return px


def building(ctx, type_, budget=12000, tex=1024, pitch=0.0, nrm=512):
    ref = _need_ref(ctx)
    obj = _load(ctx, type_, tex)
    view = ref.views[0]
    m = mask(view)
    f = spritefit.fit(sample(obj), m, ref.anchor, view.dir, pitch=pitch)
    vs.transform([obj], _matrix(f))
    ctx.stats["fit"] = {k: (round(x, 4) if isinstance(x, float) else x) for k, x in f.items() if k != "screen"}
    ctx.stats["fit"]["shift"] = [round(x, 3) for x in f["shift"]]
    high = obj.copy()
    high.data = obj.data.copy()
    bpy.context.scene.collection.objects.link(high)
    ctx.stats["triangles"] = vs.decimate(obj, budget)
    if not ctx.stats["normal_maps"]:
        # no normal map in the source: bake what the decimation took off
        ctx.stats["normal_baked_px"] = bake_normal(high, obj, nrm, obj.name)
    bpy.data.objects.remove(high, do_unlink=True)
    ctx.stats["iou"] = _final_iou(obj, m, ref.anchor, view.dir)
    ctx.stats["size_m"] = _size(obj)
    obj.parent = ctx.root
    __import__("acr_assets.ruin", fromlist=["add"]).add(ctx, obj)  # the `.ruin` state (#303, acr_assets/ruin.py)
    return obj


def _fill_blank(obj):
    """In-paints the texels Pixal3D baked plain white (faces it found no colour for) in each
    base colour image of `obj` from their neighbours (`texfill`). Returns the share of texels
    replaced (the largest over the images)."""
    from . import nature, texfill

    share = 0.0
    for mat in obj.data.materials:
        bsdf = next((n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED"), None) if mat else None
        if bsdf is None or not bsdf.inputs["Base Color"].links:
            continue
        node = bsdf.inputs["Base Color"].links[0].from_node
        img = getattr(node, "image", None)
        if img is None or not img.size[0]:
            continue
        w, h = img.size
        px = nature._pixels(img).reshape(h, w, 4)
        hole = texfill.blank(px[..., :3])
        if not hole.any():
            continue
        px[..., :3] = texfill.fill(px[..., :3], hole)
        node.image = nature._put(img, px.reshape(-1, 4), ".filled")
        node.image.pack()
        bpy.data.images.remove(img)
        share = max(share, float(hole.mean()))
    return round(share, 4)


def from_sprite(ctx, type_, budget=12000, tex=1024, nrm=512, rel=None):
    """A building generated by Pixal3D from its own `#STANDLO` sprite
    (`$ACR_SOURCES/generated/pixal3d/buildings/<Type>_sprite.glb`, local only; `rel` overrides
    the path below `generated`). The model comes out in that picture's camera frame, tilted
    towards the camera by the 30-degree elevation, so it takes the map-ruin route
    (`nature._map_fit`: turned to face the camera at -Y, `spritefit.camera_upright`, the
    residual `level`, then scale and ground shift fitted with the turn held at 0: buildings
    always face south, the sprite's own view), is decimated to `budget` (relief baked into a
    `nrm` px normal map when the source has none) and its base colour is brought up to the
    sprite's brightness as the game shades it (`nature._map_tone`; one material only).
    Texels Pixal3D baked plain white are in-painted from their neighbours first
    (`_fill_blank`, `texfill`; stats `blank_texels`, the share replaced).
    Stats as `building` plus `iou_raw`, `iou_camera`, `iou_fit`, `upright`, `tone`."""
    from . import nature

    ref = _need_ref(ctx)
    view = ref.views[0]
    m = mask(view)
    obj = _load(ctx, type_, tex, rel or f"pixal3d/buildings/{type_}_sprite.glb")
    ctx.stats["blank_texels"] = _fill_blank(obj)
    vs.transform([obj], Matrix.Rotation(math.pi, 4, "Z"))
    ctx.stats.update(nature._map_fit(obj, m, ref.anchor, view.dir))
    high = obj.copy()
    high.data = obj.data.copy()
    bpy.context.scene.collection.objects.link(high)
    ctx.stats["triangles"] = vs.decimate(obj, budget)
    if not ctx.stats["normal_maps"]:
        ctx.stats["normal_baked_px"] = bake_normal(high, obj, nrm, obj.name)
    bpy.data.objects.remove(high, do_unlink=True)
    ctx.stats["iou"] = _final_iou(obj, m, ref.anchor, view.dir)
    if len(obj.data.materials) == 1:
        ctx.stats["tone"] = nature._map_tone(obj, view)
    ctx.stats["size_m"] = _size(obj)
    obj.parent = ctx.root
    __import__("acr_assets.ruin", fromlist=["add"]).add(ctx, obj)  # the `.ruin` state (#303, acr_assets/ruin.py)
    return obj


def ship(ctx, type_, length, draft, budget=16000, tex=1024, view_dir=104.0, wreck_share=0.2, rel=None):
    ref = _need_ref(ctx)
    root = ctx.root
    root["acr_clock"] = "world"
    root["acr_machine"] = True
    obj = _load(ctx, type_, tex, rel)
    view = min(ref.views, key=lambda w: abs(w.dir - view_dir))
    m = mask(view)
    f = spritefit.fit(sample(obj), m, ref.anchor, view.dir)
    # Snap the long axis to Y, keeping the bow where the fit put it (south).
    v, _ = _arrays(obj)
    p = v @ spritefit.rot(f["yaw"], 0.0).T
    xy = p[:, :2] - p[:, :2].mean(axis=0)
    w, vec = np.linalg.eigh(xy.T @ xy)
    ax = vec[:, 1]
    turn = math.degrees(math.atan2(ax[0], ax[1]))  # angle of the long axis from +Y
    turn = (turn + 90) % 180 - 90
    yaw = f["yaw"] + turn
    p = v @ spritefit.rot(yaw, 0.0).T
    ext = p.max(axis=0) - p.min(axis=0)
    sprite_len = ext[1] * f["scale"]
    k = length / ext[1]
    lift = -p[:, 2].min() * k - draft
    cy = (p[:, 1].max() + p[:, 1].min()) / 2
    cx = (p[:, 0].max() + p[:, 0].min()) / 2
    r = Matrix([list(row) for row in spritefit.rot(yaw, 0.0)]).to_4x4()
    mat = Matrix.Translation((-cx * k, -cy * k, lift)) @ Matrix.Scale(k, 4) @ r
    vs.transform([obj], mat)
    ctx.stats["fit"] = {"yaw": round(f["yaw"], 1), "snap": round(turn, 1), "iou": round(f["iou"], 3),
                        "rough": f["rough"]}
    ctx.stats["sprite_length_m"] = round(float(sprite_len), 2)
    ctx.stats["iou_sprite_scale"] = round(f["iou"], 3)
    hull = obj
    hull.name = f"{root.name}.hull"
    vs.decimate(hull, int(budget * (1 - wreck_share)))
    wreck = vs.burnt_copy(hull, f"{root.name}.wreck", int(budget * wreck_share))
    ctx.stats["iou"] = _final_iou(hull, m, ref.anchor, view.dir)
    vs.cut_below(hull, -1.0)
    root["acr_draft"] = draft
    arm = vs.rig(root, f"{root.name}.rig", [("hull", (0, 0, 0), None), ("intact", (0, 0, 0), "hull"),
                                              ("wreck", (0, 0, 0), "hull")])
    vs.attach(hull, arm, "intact")
    vs.attach(wreck, arm, "wreck")
    sh._clips(arm, 0, length)
    zmax = max(v.co.z for v in hull.data.vertices)
    ctx.stats.update({"triangles": vs.triangles([hull, wreck]), "hull": vs.triangles([hull]),
                      "wreck": vs.triangles([wreck]), "length_m": round(length, 2),
                      "height_m": round(zmax, 2), "draft_m": round(draft, 2), "size_m": _size(hull)})
